def render(src: _Sources) -> tuple[str, list[str], dict[str, int]]:
    """The page text, its problems and the ledger totals."""
    registry = src.registry
    module_rows, members = _module_rows(src)
    ledger_rows, totals = _ledger_rows(src)
    statuses = sorted({registry.get(r).status for r in registry.ids()})
    by_status = ", ".join(f"{sum(registry.get(r).status == s for r in registry.ids())} {s}" for s in statuses)
    actual = {"recipes": len(registry.ids()), "kinds": len(registry.kinds), "cards": len(src.cards)}
    plan = "; ".join(f"{what} {actual[what]} (plan {planned})" for what, planned in PLAN_TOTALS.items())
    notes = [f"- {what}: {note}." for what, note in PLAN_NOTES.items() if actual[what] != PLAN_TOTALS[what]]
    lines = [
        MARKER,
        "# Coverage",
        "",
        "What the agent can measure, module by module, and where each capability lives (blueprint v2 §0 row 1, §1.2,",
        "§3, §9). Complete means: every in-scope mode of the installed module types is reached by a kind and a recipe,",
        "and every legacy atom, flow and command of the v0.2 taxonomy is mapped or out of scope with a written reason",
        "(`references/driver-map/`, `scripts/build_driver_map.py --check`). Regenerate with",
        "`uv run b1500 dev coverage --write`; `uv run b1500 dev coverage --check` is part of the gate.",
        "",
        (f"Totals: {len(registry.ids())} recipes ({by_status}), {len(registry.kinds)} kinds, {len(src.cards)} cards, "
         f"{len(src.rules)} rules, {len(src.stage_recipes)} bring-up stage files; ledger {totals['mapped']} mapped, "
         f"{totals['out_of_scope']} out of scope, {totals['open']} open."),
        "",
        f"Against blueprint v2 §3: {plan}.",
        *notes,
        "",
        "## Modules",
        "",
        ("Kernel rules (every plan, every module): " + _codes(KERNEL_RULES) + ". A module's recipes are those whose "
         "roles may use it (role module types, the GNDU for a ground role that allows it), whose card documents a "
         "route through the switch, or (ASU) that read the 1 pA path; the system family for the mainframe. Simulator "
         "files are under `src/b1500_test_agent/transport/sim/`."),
        "",
        *module_rows,
        "",
        "## Modes",
        "",
        ("Each in-scope measurement or operation mode, the kind that implements it and one recipe that reaches it "
         "(with the parameter that selects the mode, where one does). Checked by: what the recipe's compiled plan "
         "shows (`flex:` a FLEX preview line, `wgfmu:` a waveform channel's operation mode, `route:` a switch route; "
         "`tests/integration/test_coverage.py` compiles each), or `test:` the test that runs the path."),
        "",
        *_mode_rows(),
        "",
        "## Ledger",
        "",
        ("Legacy v0.2 atoms, flows and manual commands per family (`counts.ledger` of "
         "`references/driver-map/flex-driver-map.yaml`). The GNDU has no legacy entry."),
        "",
        *ledger_rows,
        "",
        "## Recipes",
        "",
        *_recipe_rows(src, members),
    ]
    return "\n".join(lines) + "\n", coverage_problems(src, members, totals), totals


def coverage(root: Path | None = None, *, check: bool = False) -> CoverageReport:
    """Write (or with ``check`` compare) ``docs/coverage.md`` of the repository at ``root``."""
    root = Path(root).resolve() if root is not None else find_repo_root()
    mode: Literal["check", "write"] = "check" if check else "write"
    src, problems = load_sources(root)
    if src is None:
        return CoverageReport(ok=False, mode=mode, path=COVERAGE_REL, problems=problems)
    text, problems, totals = render(src)
    target = root / COVERAGE_REL
    current = normalize_text(target.read_bytes()) if target.is_file() else None
    drift = current != text
    sizes = {"modules": len(MODULES), "recipes": len(src.registry.ids()), "kinds": len(src.registry.kinds),
             "cards": len(src.cards), "ledger": totals}
    if check or problems:
        return CoverageReport(ok=not drift and not problems, mode=mode, path=COVERAGE_REL, drift=drift,
                              problems=problems, **sizes)
    if drift:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(text.encode("utf-8"))
    return CoverageReport(ok=True, mode=mode, path=COVERAGE_REL, drift=drift, written=drift, **sizes)


def format_report(report: CoverageReport) -> str:
    """One summary line, then the problems."""
    ledger = report.ledger
    head = (f"{report.recipes} recipes, {report.kinds} kinds, {report.cards} cards, {report.modules} modules; ledger "
            f"{ledger.get('mapped', 0)} mapped, {ledger.get('out_of_scope', 0)} out of scope, "
            f"{ledger.get('open', 0)} open")
    if report.problems:
        state = "PROBLEMS" + ("; not written" if report.mode == "write" else "")
        return "\n".join([f"coverage: {len(report.problems)} {state} ({report.path}; {head})",
                          *(f"  - {p}" for p in report.problems)])
    if report.mode == "check":
        state = "DRIFT: regenerate with `uv run b1500 dev coverage --write`" if report.drift else "up to date"
        return f"coverage: {state} ({report.path}; {head})"
    return f"coverage: {'written' if report.written else 'unchanged'} ({report.path}; {head})"
