@dataclass(frozen=True)
class Module:
    """One module type or switch of the station (blueprint v2 1.1, 1.2): its ledger family (``None``: no legacy
    entry), the in-scope summary, how a recipe is found to use it, and the simulator files that model it (relative to
    ``transport/sim/``)."""

    name: str
    family: str | None
    scope: str
    uses: Callable[[Recipe, frozenset[str]], bool]
    sim: tuple[str, ...]


def _types(*names: str) -> Callable[[Recipe, frozenset[str]], bool]:
    """A recipe uses the module when a role may use one of ``names`` (``recipe_modules``)."""
    return lambda recipe, _routes: bool((recipe_modules(recipe) or set()) & set(names))


def _switch(kind: str, kinds: tuple[str, ...]) -> Callable[[Recipe, frozenset[str]], bool]:
    """A recipe uses the switch when its card documents a route through it that its roles can set and its
    measurement kind is one that routes that switch (an SMU role could reach any switch's SMU input; only these kinds
    set such routes)."""
    return lambda recipe, routes: recipe.kind in kinds and any(route.startswith(f"{kind}:") for route in routes)


def _asu(recipe: Recipe, _routes: frozenset[str]) -> bool:
    """A recipe uses the ASU when a role reads the 1 pA path (setting ``asu_1pa``, rule R-ASU-01)."""
    return any("asu_1pa" in role.settings for role in recipe.roles.values())


