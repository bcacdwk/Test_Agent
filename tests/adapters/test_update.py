def test_the_command_check_prints_the_verdict(station: Station, monkeypatch: pytest.MonkeyPatch) -> None:
    def default(**kwargs: Any) -> UpdateContext:
        ctx = station.ctx()
        ctx.say = kwargs["say"]
        return ctx

    monkeypatch.setattr(update.UpdateContext, "default", staticmethod(default))
    result = runner.invoke(app, ["update", "--check"])
    assert result.exit_code == 0, result.stdout
    assert result.stdout.rstrip().endswith("Ready.") and "versions     ok" in result.stdout
    station.set(codex={"login": False})
    result = runner.invoke(app, ["update", "--check"])
    assert result.exit_code == 1 and "Not ready. Do this:\n1. Codex is not signed in: run `codex login`" in \
        result.stdout


