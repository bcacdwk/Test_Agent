def step(report: UpdateReport, name: str) -> update.UpdateStep:
    return next(s for s in report.steps if s.step == name)


def actions(report: UpdateReport) -> str:
    return "\n".join(report.actions)


@pytest.fixture
def station(tmp_path: Path) -> Station:
    return make_station(tmp_path)


# -- the ready path, a clean pull, --continue ---------------------------------------------------------------------


def test_everything_current_is_ready_and_installs_nothing(station: Station) -> None:
    report = station.run()
    assert report.ready and report.actions == [] and update.format_verdict(report).endswith("Ready.")
    assert [s.step for s in report.steps] == list(update.STEPS)
    assert station.ran("git", "pull", "--ff-only") and station.ran("uv", "sync", "--frozen")
    assert not station.ran("npm") and not station.ran("claude", "install") and station.asked == []
    assert not station.ran("uv", "run")  # nothing pulled: no hand-over
    assert "Codex 0.170.0 = validated; Claude Code 2.1.328 = validated" in step(report, "versions").detail
    checks = step(report, "checks").detail
    for part in ("signed in: Codex, Claude Code", "no bypass default", "claude doctor: project settings valid",
                 "Codex forbids the 8 human-only commands", "trusted by Codex, Claude Code", "server starts",
                 "doctor without FAIL"):
        assert part in checks, part
    assert len(station.calls("codex")) >= 8  # execpolicy check of every human-only command
    assert any(line.startswith("versions") for line in station.lines)


@pytest.mark.parametrize("child_exit", [0, 1])
def test_a_clean_pull_syncs_and_hands_over_to_the_pulled_code(station: Station, child_exit: int) -> None:
    station.set(git={"pull": "ok"}, uv={"continue_exit": child_exit})
    report = station.run()
    assert step(report, "repo").status == "changed" and "pulled aaaaaaa..bbbbbbb (3 commit(s))" in \
        step(report, "repo").detail
    uv_calls = [row[1:] for row in station.calls("uv")]
    assert uv_calls[0][:2] == ["sync", "--frozen"]
    assert uv_calls[1][:2] == ["run", "--frozen"] and uv_calls[1][-3:] == ["b1500", "update", "--continue"]
    assert report.handed_over == child_exit and [s.step for s in report.steps][-1] == "environment"
    assert not station.ran("codex", "login")  # steps 4-8 are the pulled code's (--continue)


