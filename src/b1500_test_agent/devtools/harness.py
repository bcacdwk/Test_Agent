"""Harness wiring (blueprint 5.4): render the Codex and Claude Code MCP configs and check every harness file.

The templates in ``config/harness/`` are the single source of the two machine-specific, gitignored configs:

- ``codex``: ``config/harness/codex.config.toml`` → ``.codex/config.toml`` (example ``.codex/config.example.toml``);
- ``claude``: ``config/harness/mcp.json`` → ``.mcp.json`` (example ``.mcp.example.json``).

``b1500 harness init --codex|--claude`` replaces ``{{REPO}}`` with the clone's absolute path (POSIX separators, so
``C:/lab/test_agent`` on Windows, escaped as a JSON/TOML basic string) and ``{{NOTE}}`` with a generated-file note.
The committed examples are the same templates rendered with the placeholder ``<ABS_REPO>``.

The committed, path-free harness files are checked for their wiring, not rendered: ``.claude/settings.json`` (allow
exactly the nine other ``mcp__b1500__*`` tools plus the five read-only ``uv run b1500 manual|bringup ...`` commands
of OD-5, ``ask`` exactly ``run_confirmed_plan``, the deny rules incl. ``config init|adopt``, the ``PreToolUse`` guard
hook), ``.codex/rules/b1500.rules`` (the eight ``forbidden`` prefix rules: ``fault``, ``run --confirm``, ``config
init``, ``config adopt``, each with and without ``uv run``) and ``scripts/hooks/b1500_guard.py``. The OD-5 lines are
the owner-authorized change set of ``docs/deployment-windows.md`` "Harness permissions" (WP6.1).
``check`` reports drift between templates and rendered files and every wiring problem; ``doctor`` reuses it.
"""

from __future__ import annotations

import json
import re
import tomllib
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path, PurePath
from typing import Any, Literal

from pydantic import BaseModel, Field

from b1500_test_agent.service import TOOL_NAMES

HarnessName = Literal["codex", "claude"]

SERVER_NAME = "b1500"
ENTRY_POINT = "b1500-mcp"
ENTRY_POINT_TARGET = "b1500_test_agent.adapters.mcp_server:main"
REPO_TOKEN = "{{REPO}}"
NOTE_TOKEN = "{{NOTE}}"
EXAMPLE_REPO = "<ABS_REPO>"
GENERATED_MARK = "Generated by b1500 harness init"

CLAUDE_SETTINGS = ".claude/settings.json"
CODEX_RULES = ".codex/rules/b1500.rules"
GUARD_HOOK = "scripts/hooks/b1500_guard.py"
CONFIRM_TOOL = "run_confirmed_plan"

CODEX_DEFAULT_MODE = "auto"
CODEX_TOOL_MODES: dict[str, str] = {"run_plan": "approve", CONFIRM_TOOL: "prompt", "safe_shutdown": "approve"}
CLAUDE_ALLOW_COMMANDS = frozenset({
    "Bash(uv run b1500 manual *)", "Bash(uv run b1500 bringup status*)", "Bash(uv run b1500 bringup propose-station*)",
    "Bash(uv run b1500 bringup capture*)", "Bash(uv run b1500 bringup record*)",
})  # fmt: skip
"""Read-only CLI commands Claude Code may run without asking (owner decision OD-5, applied once at WP6.1 as written
in ``docs/deployment-windows.md`` "Harness permissions")."""
CLAUDE_ALLOW = (frozenset(f"mcp__{SERVER_NAME}__{tool}" for tool in TOOL_NAMES if tool != CONFIRM_TOOL)
                | CLAUDE_ALLOW_COMMANDS)
CLAUDE_ASK = frozenset({f"mcp__{SERVER_NAME}__{CONFIRM_TOOL}"})
CLAUDE_DENY = frozenset({
    "Bash(b1500 fault *)", "Bash(uv run b1500 fault *)", "Bash(b1500 run --confirm *)",
    "Bash(uv run b1500 run --confirm *)", "Bash(b1500 config init*)", "Bash(uv run b1500 config init*)",
    "Bash(b1500 config adopt*)", "Bash(uv run b1500 config adopt*)", "Edit(config/local/**)", "Edit(data/**)",
    "Edit(.claude/settings*.json)", "Edit(.codex/**)",
})  # fmt: skip
HOOK_TOOLS = ("Bash", "PowerShell", "Write", "Edit", "MultiEdit", "NotebookEdit")
FORBIDDEN_PREFIXES: tuple[tuple[str, ...], ...] = (
    ("b1500", "fault"), ("b1500", "run", "--confirm"),
    ("uv", "run", "b1500", "fault"), ("uv", "run", "b1500", "run", "--confirm"),
    ("b1500", "config", "init"), ("uv", "run", "b1500", "config", "init"),
    ("b1500", "config", "adopt"), ("uv", "run", "b1500", "config", "adopt"),
)  # fmt: skip


@dataclass(frozen=True)
class HarnessTarget:
    """One generated harness config: its template, gitignored output and committed example (repo-relative)."""

    name: HarnessName
    template: str
    output: str
    example: str
    init_flag: str


TARGETS: dict[HarnessName, HarnessTarget] = {
    "codex": HarnessTarget("codex", "config/harness/codex.config.toml", ".codex/config.toml",
                           ".codex/config.example.toml", "--codex"),
    "claude": HarnessTarget("claude", "config/harness/mcp.json", ".mcp.json", ".mcp.example.json", "--claude"),
}


class HarnessReport(BaseModel):
    """Result of ``harness init`` / ``harness init --check``: files written or checked and every problem found."""

    ok: bool
    repo_root: str
    written: list[str] = Field(default_factory=list, description="Files (re)written by this call.")
    unchanged: list[str] = Field(default_factory=list, description="Files already up to date.")
    checked: list[str] = Field(default_factory=list, description="Files whose content and wiring were checked.")
    problems: list[str] = Field(default_factory=list)


class Launch(BaseModel):
    """How a harness config starts the MCP server."""

    command: str
    args: list[str]


# -- rendering -------------------------------------------------------------------------------------------------------


def repo_path_text(repo_root: PurePath) -> str:
    """The clone's absolute path as written into configs: POSIX separators (``C:/lab/x`` on Windows)."""
    return repo_root.as_posix()


def escape_string(value: str) -> str:
    """``value`` as the inside of a JSON string, which is also a valid TOML basic string (TOML additionally
    forbids a raw DEL character)."""
    return json.dumps(value, ensure_ascii=False)[1:-1].replace("\x7f", "\\u007f")


def generated_note(target: HarnessTarget) -> str:
    return f"{GENERATED_MARK} {target.init_flag} for this clone; do not edit (re-run it after moving the clone)."


def example_note(target: HarnessTarget) -> str:
    return (f"Example only: uv run b1500 harness init {target.init_flag} writes {target.output} with this clone's "
            f"path for {EXAMPLE_REPO}.")


def render(target: HarnessTarget, template_text: str, repo: PurePath | None) -> str:
    """Render ``template_text`` for the clone at ``repo``; ``None`` renders the committed example."""
    if repo is None:
        return template_text.replace(NOTE_TOKEN, example_note(target)).replace(REPO_TOKEN, EXAMPLE_REPO)
    note = generated_note(target)
    return template_text.replace(NOTE_TOKEN, note).replace(REPO_TOKEN, escape_string(repo_path_text(repo)))


def _read(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


# -- wiring checks (each returns a list of problems) -----------------------------------------------------------------


def expected_launch(repo: str) -> Launch:
    """The one entry point every harness config uses: ``uv run --frozen --project <repo> b1500-mcp``."""
    return Launch(command="uv", args=["run", "--frozen", "--project", repo, ENTRY_POINT])


def _launch_problems(where: str, server: dict[str, Any], repo: str) -> list[str]:
    expected = expected_launch(repo)
    problems = []
    if server.get("command") != expected.command or server.get("args") != expected.args:
        problems.append(f"{where}: launches {server.get('command')!r} {server.get('args')!r}, expected "
                        f"{expected.command!r} {expected.args!r}")
    env = server.get("env")
    if not isinstance(env, dict) or env.get("PYTHONUTF8") != "1":
        problems.append(f"{where}: env must set PYTHONUTF8 = \"1\"")
    return problems


def codex_config_problems(text: str, repo: str, where: str = ".codex/config.toml") -> list[str]:
    """Problems of a Codex config: launch, cwd, timeouts and the per-tool approval modes of blueprint 5.4."""
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        return [f"{where}: not valid TOML ({exc})"]
    server = data.get("mcp_servers", {}).get(SERVER_NAME)
    if not isinstance(server, dict):
        return [f"{where}: no [mcp_servers.{SERVER_NAME}] table"]
    problems = _launch_problems(where, server, repo)
    if server.get("cwd") != repo:
        problems.append(f"{where}: cwd is {server.get('cwd')!r}, expected {repo!r}")
    if server.get("startup_timeout_sec") != 30 or server.get("tool_timeout_sec") != 600:
        problems.append(f"{where}: startup_timeout_sec/tool_timeout_sec must be 30/600")
    if server.get("default_tools_approval_mode") != CODEX_DEFAULT_MODE:
        problems.append(f"{where}: default_tools_approval_mode must be {CODEX_DEFAULT_MODE!r}")
    tools = server.get("tools", {})
    for tool, mode in CODEX_TOOL_MODES.items():
        actual = tools.get(tool, {}).get("approval_mode") if isinstance(tools.get(tool), dict) else None
        if actual != mode:
            problems.append(f"{where}: tools.{tool}.approval_mode is {actual!r}, expected {mode!r}")
    unknown = sorted(set(tools) - set(TOOL_NAMES)) if isinstance(tools, dict) else []
    if unknown:
        problems.append(f"{where}: approval settings for unknown tools {unknown}")
    if server.get("enabled") is False:
        problems.append(f"{where}: the server is disabled")
    return problems


def mcp_json_problems(text: str, repo: str, where: str = ".mcp.json") -> list[str]:
    """Problems of a Claude Code ``.mcp.json``: one stdio server ``b1500`` with the shared launch."""
    try:
        data = json.loads(text)
    except ValueError as exc:
        return [f"{where}: not valid JSON ({exc})"]
    servers = data.get("mcpServers") if isinstance(data, dict) else None
    server = servers.get(SERVER_NAME) if isinstance(servers, dict) else None
    if not isinstance(server, dict):
        return [f"{where}: no mcpServers.{SERVER_NAME} entry"]
    problems = _launch_problems(where, server, repo)
    if server.get("type", "stdio") != "stdio":
        problems.append(f"{where}: type must be stdio")
    return problems


def _matches(matcher: str, tool: str) -> bool:
    """Claude Code hook matcher semantics: a plain ``A|B`` list is exact names, anything else an unanchored regex."""
    if matcher in ("", "*"):
        return True
    if re.fullmatch(r"[\w\- ,|]+", matcher):
        return tool in {part.strip() for part in re.split(r"[|,]", matcher)}
    return re.search(matcher, tool) is not None


def claude_settings_problems(text: str, where: str = CLAUDE_SETTINGS) -> list[str]:
    """Problems of ``.claude/settings.json``: the blueprint 5.4 allow/ask/deny rules and the guard hook."""
    try:
        data = json.loads(text)
    except ValueError as exc:
        return [f"{where}: not valid JSON ({exc})"]
    perms = data.get("permissions", {}) if isinstance(data, dict) else {}
    allow, ask, deny = (set(perms.get(key, [])) for key in ("allow", "ask", "deny"))
    problems = []
    if allow != CLAUDE_ALLOW:
        problems.append(f"{where}: allow must be exactly {sorted(CLAUDE_ALLOW)}; extra {sorted(allow - CLAUDE_ALLOW)}, "
                        f"missing {sorted(CLAUDE_ALLOW - allow)}")
    if ask != CLAUDE_ASK:
        problems.append(f"{where}: ask must be exactly {sorted(CLAUDE_ASK)}, found {sorted(ask)}")
    if not CLAUDE_DENY <= deny:
        problems.append(f"{where}: deny lacks {sorted(CLAUDE_DENY - deny)}")
    if CLAUDE_ASK & deny:
        problems.append(f"{where}: {CONFIRM_TOOL} must be asked, not denied")
    if perms.get("defaultMode") == "bypassPermissions":
        problems.append(f"{where}: defaultMode must not be bypassPermissions")
    entries = data.get("hooks", {}).get("PreToolUse", []) if isinstance(data, dict) else []
    covered: set[str] = set()
    for entry in entries if isinstance(entries, list) else []:
        hooks = entry.get("hooks", []) if isinstance(entry, dict) else []
        if any(GUARD_HOOK in json.dumps(hook) for hook in hooks if isinstance(hook, dict)):
            covered |= {tool for tool in HOOK_TOOLS if _matches(str(entry.get("matcher", "")), tool)}
    missing = [tool for tool in HOOK_TOOLS if tool not in covered]
    if missing:
        problems.append(f"{where}: PreToolUse hook {GUARD_HOOK} does not cover {missing}")
    return problems


_RULE = re.compile(r"prefix_rule\((?P<body>.*?)\n\)", re.DOTALL)


def codex_rules_problems(text: str, where: str = CODEX_RULES) -> list[str]:
    """Problems of the Codex rules file: each forbidden prefix of blueprint 5.4 must be present."""
    forbidden: set[tuple[str, ...]] = set()
    for match in _RULE.finditer(text):
        body = match.group("body")
        pattern = re.search(r"pattern\s*=\s*(\[[^\]]*\])", body)
        if pattern and re.search(r"decision\s*=\s*\"forbidden\"", body):
            try:
                forbidden.add(tuple(json.loads(pattern.group(1))))
            except ValueError:
                continue
    missing = [list(prefix) for prefix in FORBIDDEN_PREFIXES if prefix not in forbidden]
    return [f"{where}: no forbidden prefix_rule for {missing}"] if missing else []


def entry_point_problems(repo_root: Path) -> list[str]:
    """``pyproject.toml`` must map ``b1500-mcp`` to ``adapters.mcp_server:main`` (what every config launches)."""
    try:
        data = tomllib.loads((repo_root / "pyproject.toml").read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        return [f"pyproject.toml: cannot read ({exc})"]
    target = data.get("project", {}).get("scripts", {}).get(ENTRY_POINT)
    if target != ENTRY_POINT_TARGET:
        return [f"pyproject.toml: {ENTRY_POINT} = {target!r}, expected {ENTRY_POINT_TARGET!r}"]
    return []


def launch_of(target: HarnessTarget, text: str) -> Launch | None:
    """The server launch a rendered config describes (``None`` when it cannot be parsed)."""
    try:
        if target.name == "codex":
            server = tomllib.loads(text)["mcp_servers"][SERVER_NAME]
        else:
            server = json.loads(text)["mcpServers"][SERVER_NAME]
        return Launch(command=server["command"], args=server["args"])
    except (KeyError, TypeError, ValueError, tomllib.TOMLDecodeError):
        return None


def _wiring(target: HarnessTarget, text: str, repo: str, where: str) -> list[str]:
    check = codex_config_problems if target.name == "codex" else mcp_json_problems
    return check(text, repo, where)


def committed_problems(repo_root: Path, names: Iterable[HarnessName]) -> tuple[list[str], list[str]]:
    """Checked files and problems of the committed harness files for ``names`` (templates, examples, settings,
    rules, hook script, entry point)."""
    checked: list[str] = []
    problems = entry_point_problems(repo_root)
    for name in names:
        target = TARGETS[name]
        template = _read(repo_root / target.template)
        if template is None:
            problems.append(f"{target.template}: missing (git pull)")
            continue
        example = _read(repo_root / target.example)
        checked += [target.template, target.example]
        if example is None:
            problems.append(f"{target.example}: missing (git pull)")
        elif example != render(target, template, None):
            problems.append(f"{target.example}: differs from {target.template} (b1500 harness init "
                            f"{target.init_flag} --examples)")
        problems += _wiring(target, render(target, template, None), EXAMPLE_REPO, target.template)
        extra = (CODEX_RULES, codex_rules_problems) if name == "codex" else (CLAUDE_SETTINGS, claude_settings_problems)
        path, check = extra
        text = _read(repo_root / path)
        checked.append(path)
        problems += [f"{path}: missing (git pull)"] if text is None else check(text)
        if name == "claude":
            checked.append(GUARD_HOOK)
            if not (repo_root / GUARD_HOOK).is_file():
                problems.append(f"{GUARD_HOOK}: missing (git pull)")
    return checked, problems


def rendered_problems(repo_root: Path, target: HarnessTarget) -> list[str]:
    """Drift and wiring problems of the generated config of ``target`` in ``repo_root`` (it must exist)."""
    template = _read(repo_root / target.template)
    text = _read(repo_root / target.output)
    if template is None or text is None:
        missing = target.template if template is None else target.output
        hint = "git pull" if template is None else f"b1500 harness init {target.init_flag}"
        return [f"{missing}: missing ({hint})"]
    repo = repo_path_text(repo_root)
    problems = _wiring(target, text, repo, target.output)
    if text != render(target, template, repo_root):
        problems.append(f"{target.output}: differs from {target.template} rendered for this clone (re-run b1500 "
                        f"harness init {target.init_flag})")
    return problems


# -- commands --------------------------------------------------------------------------------------------------------


def _owned(target: HarnessTarget, text: str) -> bool:
    """True when an existing output file was written by ``harness init`` (safe to overwrite)."""
    if target.name == "codex":
        return GENERATED_MARK in text
    try:
        data = json.loads(text)
    except ValueError:
        return False
    return isinstance(data, dict) and set(data) == {"mcpServers"} and set(data["mcpServers"]) == {SERVER_NAME}


def init(repo_root: Path, names: Iterable[HarnessName], *, force: bool = False,
         examples: bool = False) -> HarnessReport:
    """Render the configs for ``names`` into ``repo_root`` (and, with ``examples``, the committed examples), then
    check every harness file. An existing output not written by ``harness init`` is kept unless ``force``."""
    root = repo_root.resolve()
    selected = list(dict.fromkeys(names))
    report = HarnessReport(ok=True, repo_root=repo_path_text(root))
    for name in selected:
        target = TARGETS[name]
        template = _read(root / target.template)
        if template is None:
            report.problems.append(f"{target.template}: missing (git pull)")
            continue
        outputs = [(target.output, render(target, template, root))]
        if examples:
            outputs.append((target.example, render(target, template, None)))
        for rel, text in outputs:
            path = root / rel
            current = _read(path)
            if current == text:
                report.unchanged.append(rel)
            elif current is not None and rel == target.output and not force and not _owned(target, current):
                report.problems.append(f"{rel}: exists and was not written by b1500 harness init; move it away or "
                                       "pass --force")
            else:
                _write(path, text)
                report.written.append(rel)
    checked = check(root, selected)
    report.checked = checked.checked
    report.problems += [p for p in checked.problems if p not in report.problems]
    report.ok = not report.problems
    return report


def check(repo_root: Path, names: Iterable[HarnessName]) -> HarnessReport:
    """``harness init --check``: drift between templates and the rendered configs plus every wiring problem."""
    root = repo_root.resolve()
    selected = list(dict.fromkeys(names))
    checked, problems = committed_problems(root, selected)
    for name in selected:
        target = TARGETS[name]
        checked.append(target.output)
        problems += rendered_problems(root, target)
    return HarnessReport(ok=not problems, repo_root=repo_path_text(root), checked=checked, problems=problems)


def format_report(report: HarnessReport) -> str:
    lines = [f"harness: {'ok' if report.ok else 'PROBLEMS'} (clone {report.repo_root})"]
    lines += [f"  wrote      {rel}" for rel in report.written]
    lines += [f"  unchanged  {rel}" for rel in report.unchanged]
    if report.checked:
        lines.append("  checked    " + ", ".join(report.checked))
    lines += [f"  problem    {p}" for p in report.problems]
    return "\n".join(lines)
