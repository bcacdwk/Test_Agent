"""``b1500 update`` (v2.1 plan §2.2, WP21.1 AC): fake ``git``/``uv``/``npm``/``claude``/``codex`` executables on
``PATH`` cover every row of the step table (clean pull, dirty tree, other branch, diverged, offline, wheelhouse +
``uv.lock``, drift repaired, install yes/no, foreign install method, not signed in, bypass default, execpolicy
allows, unreadable output -> note), the guard, ``--check`` and ``--continue``; Windows paths and the PowerShell
environment by platform injection.

Each test builds a station in ``tmp_path``: a clone with the committed harness files (configs generated by
``harness init``), a home folder with the user configs of both harnesses, and the fakes (``fake_tools.py``; Codex as
an npm install, Claude Code as the native build). No real installer, network, harness or repository is touched: the
fakes log every call, and the tests assert what was and was not run.
"""

