@dataclass
class _Sources:
    """Everything the page is generated from."""

    root: Path
    registry: RecipeRegistry
    cards: list[tuple[str, CardFrontmatter]]
    examples: dict[str, str]
    stage_recipes: dict[str, set[str]]
    ledger: dict[str, dict[str, dict[str, int]]]
    scenario_models: dict[str, list[str]]
    rules: list[str]


def _load_yaml(path: Path) -> Any:
    return yaml.safe_load(path.read_text(encoding="utf-8")) if path.is_file() else None


def _example_scenarios(entry_dir: Path, cards: list[tuple[str, CardFrontmatter]]) -> dict[str, str]:
    """Card id -> the ``sim_scenario`` of its example plan (the YAML fence that names one)."""
    found: dict[str, str] = {}
    base = entry_dir / "cards"
    for rel, front in cards:
        doc = parse_markdown(base / rel, rel)
        for fence in doc.fences:
            data = yaml.safe_load(fence.body) if fence.info == "yaml" else None
            if isinstance(data, dict) and isinstance(data.get("sim_scenario"), str):
                found[front.id] = data["sim_scenario"]
                break
    return found


def _stage_recipes(root: Path) -> dict[str, set[str]]:
    """Stage id -> the recipes its stage file runs (stages without a file are left out)."""
    out: dict[str, set[str]] = {}
    for stage, (stem, _goal) in STAGES.items():
        path = root.joinpath(SOURCE_DIR, "b1500-bringup", "stages", f"{stem}.md")
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        end = text.find("\n---", 3)
        front = yaml.safe_load(text[3:end]) if text.startswith("---") and end > 0 else None
        out[stage] = set(front.get("recipes") or []) if isinstance(front, dict) else set()
    return out


def _scenario_models(root: Path) -> dict[str, list[str]]:
    """Scenario name -> the device models it declares (``models.<device>.model``)."""
    out: dict[str, list[str]] = {}
    for path in sorted((root / SCENARIOS_REL).glob("*.yaml")):
        data = _load_yaml(path)
        models = data.get("models") if isinstance(data, dict) else None
        names = [m.get("model") for m in (models or {}).values() if isinstance(m, dict)]
        out[path.stem] = sorted({n for n in names if isinstance(n, str)})
    return out


def load_sources(root: Path) -> tuple[_Sources | None, list[str]]:
    """The sources of the page under ``root`` and the problems that stop generation (card frontmatter)."""
    entry_dir = root / SOURCE_DIR / ENTRY_SKILL
    cards, problems = collect_cards(entry_dir)
    if problems:
        return None, [f"card frontmatter: {p}" for p in problems]
    registry = RecipeRegistry.load(root / "recipes", repo_root=root)
    ledger_doc = _load_yaml(root / LEDGER_REL)
    ledger = ledger_doc.get("counts", {}).get("ledger", {}) if isinstance(ledger_doc, dict) else {}
    return _Sources(root=root, registry=registry, cards=cards, examples=_example_scenarios(entry_dir, cards),
                    stage_recipes=_stage_recipes(root), ledger=ledger, scenario_models=_scenario_models(root),
                    rules=[spec.rule_id for spec in registered_rules()]), []


# -- derived views -----------------------------------------------------------------------------------------------------


def _card_of(src: _Sources) -> dict[str, tuple[str, CardFrontmatter]]:
    """Recipe id -> (card rel path, frontmatter) of the card that lists it."""
    return {recipe: (rel, front) for rel, front in src.cards for recipe in front.recipes}


def _routes(src: _Sources, recipe: Recipe, card: CardFrontmatter | None) -> frozenset[str]:
    """The switch routes a recipe uses: its card's documented routes that its own roles (or kind) can set."""
    if card is None:
        return frozenset()
    return frozenset(set(card.routes) & recipe_routes(recipe, src.registry.kinds.get(recipe.kind)))


def _stage(recipe_id: str, card: CardFrontmatter | None) -> str | None:
    """The bring-up stage of a carded recipe (``None`` without a card)."""
    return card.stage_of(recipe_id) if card is not None else None


def _codes(items: list[str] | set[str] | tuple[str, ...]) -> str:
    return ", ".join(f"`{i}`" for i in items) or "-"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _module_rows(src: _Sources) -> tuple[list[str], dict[str, list[str]]]:
    """The module table and the recipes of every module."""
    cards = _card_of(src)
    members: dict[str, list[str]] = {}
    rows = [("| Module | Ledger family | In scope (blueprint v2 1.2) | Kinds | Recipes | Cards | Rules (besides the "
             "kernel) | Simulator | Example scenarios (device models) | Stages |"),
            "|---|---|---|---|---|---|---|---|---|---|"]
    for module in MODULES:
        ids: list[str] = []
        for recipe_id in src.registry.ids():
            recipe = src.registry.get(recipe_id)
            card = cards.get(recipe_id, (None, None))[1]
            if module.uses(recipe, _routes(src, recipe, card)):
                ids.append(recipe_id)
        members[module.name] = ids
        kinds = sorted({src.registry.get(r).kind for r in ids})
        card_ids = sorted({cards[r][1].id for r in ids if r in cards})
        stages = sorted({s for r in ids if (s := _stage(r, cards.get(r, (None, None))[1]))},
                        key=list(STAGES).index)
        scenarios = sorted({src.examples[c] for c in card_ids if c in src.examples})
        scen = ", ".join(f"`{s}` ({', '.join(src.scenario_models.get(s, [])) or '-'})" for s in scenarios) or "-"
        rows.append(f"| {module.name} | {module.family or '- (no legacy entry)'} | {_cell(module.scope)} | "
                    f"{_codes(kinds)} | {len(ids)} | {_codes(card_ids)} | {_codes(MODULE_RULES[module.name])} | "
                    f"{_codes(module.sim)} | {scen} | {', '.join(stages) or '-'} |")
    return rows, members


def _mode_rows() -> list[str]:
    rows = ["| Module | Mode | Kind | Reached by | Checked by |", "|---|---|---|---|---|"]
    rows += [f"| {m.module} | {_cell(m.mode)} | `{m.kind}` | `{m.recipe}` | `{_cell(m.marker)}` |" for m in MODES]
    return rows


LEDGER_KINDS: Final = ("atoms", "flows", "commands")


def _ledger_rows(src: _Sources) -> tuple[list[str], dict[str, int]]:
    """Per family and entry type mapped / out of scope / open, a total row, and the totals per scope."""
    totals = dict.fromkeys(SCOPES, 0)
    per_kind = {kind: dict.fromkeys(SCOPES, 0) for kind in LEDGER_KINDS}
    rows = ["| Family | Atoms (mapped / out of scope / open) | Flows | Commands |", "|---|---|---|---|"]
    for family in LEDGER_FAMILIES:
        cells = []
        for kind in LEDGER_KINDS:
            counts = src.ledger.get(family, {}).get(kind, {})
            cells.append(" / ".join(str(counts.get(scope, 0)) for scope in SCOPES))
            for scope in SCOPES:
                totals[scope] += counts.get(scope, 0)
                per_kind[kind][scope] += counts.get(scope, 0)
        rows.append(f"| {family} | {' | '.join(cells)} |")
    rows.append("| total | " + " | ".join(" / ".join(str(per_kind[k][s]) for s in SCOPES) for k in LEDGER_KINDS)
                + " |")
    return rows, totals


def _recipe_rows(src: _Sources, members: dict[str, list[str]]) -> list[str]:
    cards = _card_of(src)
    rows = ["| Recipe | Family | Kind | Status | Card | Stage | Modules |", "|---|---|---|---|---|---|---|"]
    for recipe_id in src.registry.ids():
        recipe = src.registry.get(recipe_id)
        _rel, card = cards.get(recipe_id, (None, None))
        card_cell = f"`{card.family}/{card.id}`" if card is not None else (
            "none by design" if recipe_id in CARDLESS_RECIPES else "-")
        modules = [m.name.split(" (")[0] for m in MODULES if recipe_id in members[m.name]]
        rows.append(f"| `{recipe_id}` | {recipe.family} | `{recipe.kind}` | {recipe.status} | {card_cell} | "
                    f"{_stage(recipe_id, card) or '-'} | {', '.join(modules)} |")
    return rows


# -- problems ----------------------------------------------------------------------------------------------------------


def coverage_problems(src: _Sources, members: dict[str, list[str]], totals: dict[str, int]) -> list[str]:
    """Every coverage gap (module docstring)."""
    problems: list[str] = []
    registry = src.registry
    problems += [f"recipe tree: {p}" for p in registry.problems()]
    problems += [f"module {name}: no recipe uses it" for name, ids in members.items() if not ids]
    used_kinds = {registry.get(r).kind for r in registry.ids()}
    problems += [f"kind {k}: no recipe uses it" for k in sorted(set(registry.kinds) - used_kinds)]
    listed = set(KERNEL_RULES).union(*MODULE_RULES.values())
    problems += [f"rule {r}: in no rule table (KERNEL_RULES or MODULE_RULES)" for r in src.rules if r not in listed]
    problems += [f"rule {r}: listed but not registered" for r in sorted(listed - set(src.rules))]
    sim = src.root / SIM_PACKAGE_REL
    problems += [f"module {m.name}: simulator file {f} does not exist" for m in MODULES for f in m.sim
                 if not (sim / f).is_file()]
    names = {m.name for m in MODULES}
    for mode in MODES:
        if mode.module not in names:
            problems.append(f"mode {mode.mode}: unknown module {mode.module}")
        if mode.recipe not in registry.ids():
            problems.append(f"mode {mode.mode}: recipe {mode.recipe} is not registered")
        elif registry.get(mode.recipe).kind != mode.kind:
            problems.append(f"mode {mode.mode}: recipe {mode.recipe} has kind {registry.get(mode.recipe).kind}, "
                            f"not {mode.kind}")
        elif not re.match(r"^(flex:.+|wgfmu:(dc|fastiv|pg|smu)|route:[a-z0-9_]+:[a-z_]+|test:tests/.+\.py::\w+)$",
                          mode.marker):
            problems.append(f"mode {mode.mode}: marker {mode.marker!r} is not flex:/wgfmu:/route:/test:")
        elif mode.marker.startswith("test:"):
            path, _, name = mode.marker.removeprefix("test:").partition("::")
            test_file = src.root / path
            if not test_file.is_file() or f"def {name}(" not in test_file.read_text(encoding="utf-8"):
                problems.append(f"mode {mode.mode}: test {mode.marker.removeprefix('test:')} does not exist")
    missing = [f for f in LEDGER_FAMILIES if f not in src.ledger]
    if missing:
        problems.append(f"ledger: no counts for {missing} in {LEDGER_REL} (run scripts/build_driver_map.py)")
    if totals.get("open"):
        problems.append(f"ledger: {totals['open']} entries are still open (map them or give an out-of-scope reason "
                        "in scripts/build_driver_map.py)")
    cards = _card_of(src)
    for recipe_id in registry.ids():
        if recipe_id not in cards:
            if recipe_id not in CARDLESS_RECIPES:
                problems.append(f"recipe {recipe_id}: no card")
            continue
        stage = cards[recipe_id][1].stage_of(recipe_id)
        if recipe_id not in src.stage_recipes.get(stage, set()):
            problems.append(f"recipe {recipe_id}: bring-up stage {stage} has no stage file that runs it")
    actual = {"recipes": len(registry.ids()), "kinds": len(registry.kinds), "cards": len(src.cards)}
    problems += [f"{what}: {actual[what]} in the tree, {planned} in blueprint v2 3, and no PLAN_NOTES entry says why"
                 for what, planned in PLAN_TOTALS.items() if actual[what] != planned and what not in PLAN_NOTES]
    return problems


