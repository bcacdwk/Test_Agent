"""Generate ``C_SIGNATURES``, the C prototypes of the WGFMU DLL binding
(``src/b1500_test_agent/transport/wgfmu/dll.py``, blueprint v2 2.4; WP10.2), from the API extract
``references/manuals/structured/b1530a-wgfmu-api-reference.yaml``.

For every C function the protocol uses (``transport.wgfmu.api.C_FUNCTIONS``):

1. the extract item that documents it (its ``name`` lists the function; an undocumented function is an error);
2. its prototype, the "Syntax int WGFMU_x(...);" line on the manual pages the item cites (``pdf_pages``, Ed. 5 =
   corpus document WG5, the extract's source), read from the committed manual corpus
   (``references/manuals/corpus/``): parameter order and C types;
3. checks: the base type of every parameter (``int``, ``double``, ``char``) is one the extract lists for the item, and
   the same prototype appears in Ed. 8 (corpus document WG, the library generation of the lab, A.03.00 and later).

The table is written between the ``BEGIN GENERATED``/``END GENERATED`` markers of ``dll.py``; the unit test
``tests/wgfmu_abi/test_signatures.py`` regenerates it and compares.

Usage (from the repo root):
    uv run python scripts/gen_wgfmu_signatures.py           # rewrite the generated block
    uv run python scripts/gen_wgfmu_signatures.py --check   # exit 1 when the block is not current
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
API_YAML = REPO_ROOT / "references" / "manuals" / "structured" / "b1530a-wgfmu-api-reference.yaml"
TARGET = REPO_ROOT / "src" / "b1500_test_agent" / "transport" / "wgfmu" / "dll.py"
BEGIN = "# BEGIN GENERATED by scripts/gen_wgfmu_signatures.py from the WGFMU API extract; do not edit by hand"
END = "# END GENERATED"
EXTRACT_DOC = "WG5"
"""Corpus document of the extract's page numbers (``source.edition`` Edition 5)."""
CURRENT_DOC = "WG"
"""Corpus document of the current guide (Ed. 8): the prototypes must agree."""

PROTOTYPE = re.compile(r"Syntax\s+int\s+(WGFMU_\w+)\s*\(([^)]*)\)\s*;")
C_TYPES = ("int", "double", "const char*", "char*", "int*", "double*")
"""The parameter types the binding maps to ctypes (``transport.wgfmu.dll.C_TYPES``)."""


class SignatureError(Exception):
    """The extract, the corpus and the binding do not agree."""


def _display(path: Path) -> str:
    try:
        return path.relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def _base(c_type: str) -> str:
    """``const char*`` -> ``char``, ``int*`` / ``int[]`` -> ``int``, ``string`` -> ``char`` ..."""
    text = c_type.replace("const", "").replace("*", "").replace("[]", "").strip()
    return "char" if text == "string" else text


def parse_parameters(text: str) -> tuple[tuple[str, str], ...]:
    """``(c_type, name)`` of each parameter of a prototype's parameter list (``""`` and ``void`` = none)."""
    flat = " ".join(text.split())
    if flat in ("", "void"):
        return ()
    found = []
    for part in flat.split(","):
        match = re.fullmatch(r"(.+?)\s*\b(\w+)", part.strip())
        if match is None:
            raise SignatureError(f"cannot parse parameter {part!r}")
        c_type = re.sub(r"\s*\*", "*", match.group(1).strip())
        if c_type not in C_TYPES:
            raise SignatureError(f"parameter {part!r}: type {c_type!r} is not one of {C_TYPES}")
        found.append((c_type, match.group(2)))
    return tuple(found)


def load_items(path: Path = API_YAML) -> list[dict[str, Any]]:
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    return [item for item in data["api_items"] if item.get("type") == "function"]


def item_for(name: str, items: list[dict[str, Any]]) -> dict[str, Any]:
    for item in items:
        if name in (part.strip() for part in item["name"].split("/")):
            return item
    raise SignatureError(f"{name} is not documented in {_display(API_YAML)}")


def extract_bases(item: dict[str, Any]) -> set[str]:
    """Base types of every parameter alternative the extract lists for ``item``."""
    bases = set()
    for param in item.get("parameters") or []:
        for alternative in str(param.get("type", "")).split(" or "):
            base = _base(alternative)
            if base in ("int", "double", "char"):
                bases.add(base)
    return bases


def _corpus() -> Any:
    sys.path.insert(0, str(REPO_ROOT / "src"))
    from b1500_test_agent.manuals.catalog import ManualPaths
    from b1500_test_agent.manuals.search import Corpus

    corpus = Corpus.load(ManualPaths.for_repo(REPO_ROOT))
    if corpus is None:
        raise SignatureError("the manual corpus is missing (references/manuals/corpus/; git pull)")
    return corpus


def prototypes(corpus: Any, doc: str, pages: list[int] | None = None) -> dict[str, str]:
    """C function -> parameter list text of every prototype on ``pages`` of ``doc`` (all pages when ``None``); a
    prototype that runs onto the next page is read across the page break."""
    texts = {page.p: page.text for page in corpus.doc_pages(doc)}
    wanted = sorted(texts) if pages is None else [p for p in pages if p in texts]
    found: dict[str, str] = {}
    for p in wanted:
        text = texts[p] + "\n" + texts.get(p + 1, "")
        for match in PROTOTYPE.finditer(text):
            found.setdefault(match.group(1), " ".join(match.group(2).split()))
    return found


def signature(parameters: str) -> tuple[str, ...]:
    """The C types of a prototype's parameter list."""
    return tuple(c_type for c_type, _ in parse_parameters(parameters))


def used_functions() -> list[str]:
    sys.path.insert(0, str(REPO_ROOT / "src"))
    from b1500_test_agent.transport.wgfmu.api import C_FUNCTIONS

    return sorted({name for names in C_FUNCTIONS.values() for name in names})


def build(items: list[dict[str, Any]] | None = None, corpus: Any = None) -> dict[str, tuple[str, ...]]:
    """The table (see the module docstring); raises ``SignatureError`` listing every disagreement."""
    items = load_items() if items is None else items
    corpus = _corpus() if corpus is None else corpus
    current = prototypes(corpus, CURRENT_DOC)
    table: dict[str, tuple[str, ...]] = {}
    problems = []
    for name in used_functions():
        try:
            item = item_for(name, items)
        except SignatureError as exc:
            problems.append(str(exc))
            continue
        cited = prototypes(corpus, EXTRACT_DOC, [int(p) for p in item.get("pdf_pages") or []])
        if name not in cited:
            problems.append(f"{name}: no prototype on {EXTRACT_DOC} pages {item.get('pdf_pages')} cited by the "
                            f"extract item {item['name']!r}")
            continue
        try:
            types = signature(cited[name])
            newer = signature(current[name]) if name in current else None
        except SignatureError as exc:
            problems.append(f"{name}: {exc}")
            continue
        allowed = extract_bases(item)
        wrong = [t for t in types if _base(t) not in allowed]
        if wrong:
            problems.append(f"{name}: parameter types {wrong} not among the extract's {sorted(allowed)}")
        if newer != types:
            problems.append(f"{name}: Ed. 5 prototype {types} differs from Ed. 8 ({newer})")
        table[name] = types
    if problems:
        raise SignatureError("\n".join(problems))
    return table


def render(table: dict[str, tuple[str, ...]]) -> str:
    """The generated block, markers included."""
    lines = [BEGIN, "C_SIGNATURES: Final[dict[str, tuple[str, ...]]] = {"]
    for name, signature in table.items():
        args = ", ".join(f'"{t}"' for t in signature)
        lines.append(f'    "{name}": ({args}{"," if len(signature) == 1 else ""}),')
    lines += ["}", END]
    return "\n".join(lines)


def splice(source: str, block: str) -> str:
    start, stop = source.find(BEGIN), source.find(END)
    if start < 0 or stop < start:
        raise SignatureError(f"{_display(TARGET)} has no generated block markers")
    return source[:start] + block + source[stop + len(END):]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the generated block is not current")
    args = parser.parse_args(argv)
    try:
        table = build()
        source = TARGET.read_text(encoding="utf-8")
        updated = splice(source, render(table))
    except SignatureError as exc:
        print(f"gen_wgfmu_signatures: {exc}", file=sys.stderr)
        return 1
    rel = _display(TARGET)
    if args.check:
        if updated != source:
            print(f"{rel}: C_SIGNATURES is not current; run uv run python scripts/gen_wgfmu_signatures.py",
                  file=sys.stderr)
            return 1
        print(f"{rel}: C_SIGNATURES current ({len(table)} functions)")
        return 0
    if updated != source:
        TARGET.write_text(updated, encoding="utf-8", newline="\n")
    print(f"{rel}: C_SIGNATURES written ({len(table)} functions)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
