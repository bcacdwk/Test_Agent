    def measure_values(self, ch: int, offset: int, size: int) -> tuple[np.ndarray, np.ndarray]:
        """Up to ``size`` values from ``offset``, read in chunks of ``READBACK_CHUNK`` into numpy buffers."""
        fn = "measure_values"
        channel, first, wanted = _int(fn, ch, "channel"), _int(fn, offset, "offset"), _int(fn, size, "size")
        if wanted < 1:
            raise _refuse(fn, PARAMETER_OUT_OF_RANGE, f"size {size!r}")
        times, values = np.empty(wanted, dtype=np.float64), np.empty(wanted, dtype=np.float64)
        done = 0
        while done < wanted:
            chunk = min(READBACK_CHUNK, wanted - done)
            length = ctypes.c_int(chunk)
            t_view, v_view = times[done:], values[done:]
            try:
                self._call(fn, "WGFMU_getMeasureValues", channel, _int(fn, first + done, "offset"),
                           ctypes.byref(length), _ptr(t_view, _DOUBLE_P), _ptr(v_view, _DOUBLE_P))
            except WgfmuError as exc:
                if done > 0 and exc.rc in (RESULT_NOT_READY, PARAMETER_OUT_OF_RANGE):
                    # the data end inside this chunk (not measured yet, or the last value was read): return what was
                    # read, as one library call would; the chunk's own error string is not a failure of the read
                    if self._taken and self._taken[-1] == exc.text:
                        self._taken.pop()
                    break
                raise
            got = max(0, min(length.value, chunk))
            done += got
            if got < chunk:
                break
        return times[:done].copy(), values[:done].copy()

