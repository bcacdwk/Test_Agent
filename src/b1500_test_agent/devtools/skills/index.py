"""``b1500 dev gen-index [--check]``: the GENERATED card index ``.agents/skills/b1500-test/cards/README.md``
(blueprint v2 6.1, 6.2).

One section per family (``## smu`` ... ``## system``, in ``Recipe.family`` order; the entry skill's family router
links ``cards/README.md#<family>``), each with one table ``family | intent keywords | card | recipes | status |
modules | stage``: a row per card (from its frontmatter; status = the recipes' effective status on the simulator from
the registry), then a row per runnable recipe without a card (``CARDLESS_RECIPES``) and per reserved
(``not_implemented``) recipe of the family, which point at ``reserved/README.md`` until WP11.2.

The text is a pure function of the card frontmatter and the registry: UTF-8, LF line endings, no timestamps, so
``--check`` (and the ``card_index`` problem of ``lint-skills``) compares bytes. ``gen-index`` refuses to write while
a card's frontmatter is invalid (the index would silently lose that card).
"""


from __future__ import annotations

from pathlib import Path
from typing import Literal

from pydantic import Field, ValidationError

from b1500_test_agent.catalog.registry import RecipeRegistry
from b1500_test_agent.devtools.skills.cards import find_card_paths
from b1500_test_agent.devtools.skills.common import (
    CARDLESS_RECIPES,
    CARDS_DIR,
    ENTRY_SKILL,
    FAMILIES,
    README,
    RESERVED_DIR,
    CardFrontmatter,
    Lint,
    validation_messages,
)
from b1500_test_agent.devtools.skills.markdown import parse_markdown
from b1500_test_agent.devtools.sync_harness import SOURCE_DIR, normalize_text
from b1500_test_agent.models.common import StrictModel
from b1500_test_agent.paths import find_repo_root

INDEX_REL = f"{SOURCE_DIR}/{ENTRY_SKILL}/{CARDS_DIR}/{README}"
INDEX_MARKER = ("<!-- GENERATED by `uv run b1500 dev gen-index` from the card frontmatter and recipes/; edit the "
                "cards, then regenerate -->")
FAMILY_SCOPE: dict[str, str] = {
    "smu": "SMU I-V with HRSMU/MPSMU and the GNDU: contact and resistance, diode, MOSFET DC, leakage, spot/Kelvin, "
           "pulsed, sampling, search.",
    "cmu": "MFCMU (SCUU when declared): corrections, C-V, C-f, C-t, Dit, split C-V.",
    "spgu": "HV-SPGU pulses through the 16440A selectors: pulse trains, selector check, charge pumping.",
    "wgfmu": "WGFMU with RSU: fast pulsed I-V, pulse trains, RTN and 1/f noise, custom waveforms.",
    "nvm": "Ferroelectric memory: FeFET memory window, program/read, switching kinetics, endurance, retention; "
           "FeCap PUND.",
    "reliability": "Stress-measure: BTI, HCI, SILC, TDDB, breakdown voltage, IGZO bias stress (destructive ones "
                   "always confirmed).",
    "system": "Instrument maintenance: self-test, self-calibration, zero check.",
}
"""One-line scope of each family section."""
HEADER = ("| family | intent keywords | card | recipes | status | modules | stage |",
          "|---|---|---|---|---|---|---|")


def _cell(text: str) -> str:
    """Table-cell text: one line, ``|`` and ``*`` escaped (``*TST?`` is no emphasis)."""
    return " ".join(text.split()).replace("|", "\\|").replace("*", "\\*")


def _codes(ids: list[str]) -> str:
    return ", ".join(f"`{i}`" for i in ids)


def render_index(cards: list[tuple[str, CardFrontmatter]], registry: RecipeRegistry) -> str:
    """The index text; ``cards`` = (path relative to ``cards/`` in POSIX form, frontmatter) of every card."""
    lines = [
        INDEX_MARKER,
        "# Test-card index",
        "",
        "Pick the family, then the card by its intent keywords; read the card before planning. Status = effective",
        "status on the simulator (`list_recipes` on the current backend wins; on hardware a recipe needs",
        "`first_hw_run` confirmation until `hw_validated`). Stage = bring-up stage (skill `b1500-bringup`). A",
        "`not_implemented` recipe is reserved: say so, offer the card the reserved list names, never emulate it.",
        "",
        "Families: " + " · ".join(f"[{family}](#{family})" for family in FAMILIES),
    ]
    carded = {recipe for _rel, front in cards for recipe in front.recipes}
    for family in FAMILIES:
        lines += ["", f"## {family}", "", FAMILY_SCOPE[family], ""]
        rows: list[str] = []
        for rel, front in sorted((c for c in cards if c[1].family == family), key=lambda c: c[1].id):
            statuses = list(dict.fromkeys(registry.effective_status(r, "sim") if r in registry.ids() else "unknown"
                                          for r in front.recipes))
            rows.append(f"| {family} | {_cell(', '.join(front.intent))} | [{front.id}]({rel}) | "
                        f"{_codes(front.recipes)} | {', '.join(statuses)} | "
                        f"{', '.join(front.modules) or 'all installed'} | {front.bringup_stage} |")
        others = [registry.get(r) for r in registry.ids() if r not in carded and registry.get(r).family == family]
        for recipe in sorted((r for r in others if r.status != "not_implemented"), key=lambda r: r.id):
            reason = "no card by design: ask the human first" if recipe.id in CARDLESS_RECIPES else "no card yet"
            rows.append(f"| {family} | {_cell(recipe.title)} | {reason} | `{recipe.id}` | "
                        f"{registry.effective_status(recipe.id, 'sim')} | - | - |")
        for recipe in sorted((r for r in others if r.status == "not_implemented"), key=lambda r: r.id):
            rows.append(f"| {family} | reserved: {_cell(recipe.title)} | [reserved]({RESERVED_DIR}/{README}) | "
                        f"`{recipe.id}` | not_implemented | - | - |")
        if rows:
            lines += [*HEADER, *rows]
        else:
            lines.append("No recipe in this family yet: say so; never emulate it with another family's recipe.")
    return "\n".join(lines) + "\n"


class IndexReport(StrictModel):
    """Outcome of ``gen-index``: ``ok`` iff there are no problems and (``check``) no drift / (write) written."""

    ok: bool
    mode: Literal["check", "write"]
    path: str
    cards: int = 0
    drift: bool = False
    written: bool = False
    problems: list[str] = Field(default_factory=list)


def collect_cards(entry_dir: Path) -> tuple[list[tuple[str, CardFrontmatter]], list[str]]:
    """(rel path, frontmatter) of every card under ``entry_dir/cards`` and the frontmatter problems."""
    cards: list[tuple[str, CardFrontmatter]] = []
    problems: list[str] = []
    base = entry_dir / CARDS_DIR
    for path in find_card_paths(entry_dir):
        rel = path.relative_to(base).as_posix()
        try:
            doc = parse_markdown(path, rel)
        except (OSError, UnicodeDecodeError) as exc:
            problems.append(f"{rel}: cannot read: {exc}")
            continue
        if not isinstance(doc.front, dict) or doc.front_error:
            problems.append(f"{rel}: frontmatter missing or invalid {doc.front_error or ''}".rstrip())
            continue
        try:
            cards.append((rel, CardFrontmatter.model_validate(doc.front)))
        except ValidationError as exc:
            problems.extend(f"{rel}: {message}" for message in validation_messages(exc))
    return cards, problems


def gen_index(root: Path | None = None, *, check: bool = False, recipes_dir: Path | None = None) -> IndexReport:
    """Write (or with ``check`` compare) the card index of the repository at ``root``."""
    root = Path(root).resolve() if root is not None else find_repo_root()
    target = root / INDEX_REL
    mode: Literal["check", "write"] = "check" if check else "write"
    entry_dir = root / SOURCE_DIR / ENTRY_SKILL
    cards, problems = collect_cards(entry_dir)
    registry = RecipeRegistry.load(Path(recipes_dir) if recipes_dir else root / "recipes", repo_root=root)
    if problems:
        return IndexReport(ok=False, mode=mode, path=INDEX_REL, cards=len(cards), problems=problems)
    text = render_index(cards, registry)
    current = normalize_text(target.read_bytes()) if target.is_file() else None
    drift = current != text
    if check:
        return IndexReport(ok=not drift, mode=mode, path=INDEX_REL, cards=len(cards), drift=drift)
    if drift:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(text.encode("utf-8"))
    return IndexReport(ok=True, mode=mode, path=INDEX_REL, cards=len(cards), drift=drift, written=drift)


def format_report(report: IndexReport) -> str:
    if report.problems:
        return "\n".join([f"card index: {len(report.problems)} PROBLEM(S); {report.path} not written",
                          *(f"  {p}" for p in report.problems)])
    if report.mode == "check":
        state = "DRIFT: regenerate with `uv run b1500 dev gen-index`" if report.drift else "up to date"
        return f"card index: {state} ({report.path}, {report.cards} cards)"
    state = "written" if report.written else "unchanged"
    return f"card index: {state} ({report.path}, {report.cards} cards)"


def check_index(lint: Lint, entry_dir: Path, cards: list[tuple[str, CardFrontmatter]],
                registry: RecipeRegistry) -> None:
    """``card_index`` problem when ``cards/README.md`` differs from the generated text (first differing line)."""
    path = entry_dir / CARDS_DIR / README
    text = render_index(cards, registry)
    if not path.is_file():
        lint.add("card_index", path, "the generated card index is missing (run `uv run b1500 dev gen-index`)")
        return
    current = normalize_text(path.read_bytes())
    if current == text:
        return
    have, want = current.split("\n"), text.split("\n")
    line = next((i for i, (a, b) in enumerate(zip(have, want, strict=False)) if a != b), min(len(have), len(want)))
    expected = want[line] if line < len(want) else "<end of file>"
    lint.add("card_index", path, f"out of date (run `uv run b1500 dev gen-index`); line {line + 1} should read: "
                                 f"{expected[:160]}", line + 1)
