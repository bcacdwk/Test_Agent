class WgfmuDll:
    """``WgfmuApi`` over ``wgfmu.dll`` (see the module docstring). ``path``: the library file (``library_path``);
    ``loader``: replaces ``ctypes.WinDLL`` (tests: a ctypes-shaped fake library); ``platform``/``bits``: replace
    ``sys.platform`` and this interpreter's pointer width in the probe (platform-injected tests)."""

    def __init__(self, path: str, *, loader: Loader | None = None, platform: str | None = None,
                 bits: int | None = None) -> None:
        self.path = path
        self.platform = sys.platform if platform is None else platform
        self.bits = python_bits() if bits is None else bits
        self._loader = loader
        self._lib: Any = None
        self.last_detail = ""
        """Detail string of the last ``self_test``/``self_calibration``."""
        self._taken: list[str] = []
        """Error strings read from the library while raising ``WgfmuError``; ``errors()`` returns them first."""

    @classmethod
    def locate(cls, settings: Settings | WgfmuSettings, *, platform: str | None = None,
               environ: Mapping[str, str] | None = None, bits: int | None = None) -> DllProbe:
        """Probe the library ``settings`` selects (``library_path``); never raises, loads nothing."""
        return probe_library(library_path(settings, environ), platform=platform, bits=bits)

    def probe(self) -> DllProbe:
        """Probe this binding's library file (cached while the file is unchanged); never raises, loads nothing."""
        return probe_library(self.path, platform=self.platform, bits=self.bits)

    @property
    def loaded(self) -> bool:
        """True once the library was loaded (the first call)."""
        return self._lib is not None

    def _library(self, fn: str) -> Any:
        if self._lib is not None:
            return self._lib
        probe = self.probe()
        if not probe.loadable:
            raise WgfmuError(LIBRARY_ERROR, f"{fn}: {error_text(LIBRARY_ERROR, f'not loaded: {probe.message}')}",
                             function=fn)
        try:
            lib = (self._loader or _win_dll)(self.path)
        except OSError as exc:
            raise WgfmuError(LIBRARY_ERROR, f"{fn}: {error_text(LIBRARY_ERROR, f'cannot load {self.path}: {exc}')}",
                             function=fn) from None
        try:
            bind_library(lib, self.path)
        except WgfmuError as exc:
            raise WgfmuError(exc.wgfmu_code, f"{fn}: {exc.text}", function=fn) from None
        self._lib = lib
        return lib

    def _call(self, fn: str, name: str, *args: Any) -> int:
        """Call C function ``name`` for protocol method ``fn``; a negative return code raises ``WgfmuError``."""
        lib = self._library(fn)
        try:
            rc = getattr(lib, name)(*args)
        except Exception as exc:  # access violation (OSError), ctypes.ArgumentError: a library failure
            detail = f"{name} raised {type(exc).__name__}: {exc}"
            raise WgfmuError(LIBRARY_ERROR, f"{fn}: {error_text(LIBRARY_ERROR, detail)}", function=fn) from exc
        rc = int(rc)
        if rc < 0:
            raise self._failure(fn, rc)
        return rc

    def _failure(self, fn: str, rc: int) -> WgfmuError:
        """The ``WgfmuError`` of a negative return code: the library's queued error strings are read now (the last
        one belongs to this call) and kept for ``errors()``, so the queue looks as if they were never read."""
        strings = self._drain_errors()
        self._taken.extend(strings)
        text = strings[-1] if strings else ""
        code = rc
        if rc == FW_ERROR:
            found = FIRMWARE_CODE.search(text)
            if found is not None:
                code = int(found.group(1))
        return WgfmuError(code, text or f"{fn}: {error_text(code)}", rc=rc, function=fn)

    def _drain_errors(self) -> list[str]:
        """Every error string in the library's queue, oldest first (failures to read end the drain quietly)."""
        lib = self._lib
        found: list[str] = []
        try:
            for _ in range(MAX_ERRORS):
                size = ctypes.c_int(0)
                if int(lib.WGFMU_getErrorSize(ctypes.byref(size))) < 0 or size.value <= 0:
                    break
                buffer = ctypes.create_string_buffer(size.value + 1)
                length = ctypes.c_int(size.value + 1)
                if int(lib.WGFMU_getError(buffer, ctypes.byref(length))) < 0:
                    break
                found.append(buffer.value.decode("ascii", errors="replace").strip())
        except Exception:  # noqa: BLE001 - the original failure is reported either way
            return found
        return found

