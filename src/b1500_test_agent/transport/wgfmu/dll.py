def argtypes_of(name: str) -> list[Any]:
    """The ctypes ``argtypes`` of C function ``name`` (from ``C_SIGNATURES``)."""
    return [C_TYPES[t] for t in C_SIGNATURES[name]]


def _win_dll(path: str) -> Any:
    """``ctypes.WinDLL(path)`` (``stdcall`` convention of ``wgfmu.h``; the same as ``cdecl`` on x64)."""
    loader = getattr(ctypes, "WinDLL", None)
    if loader is None:
        raise OSError("ctypes.WinDLL exists only on Windows")
    return loader(path)


def bind_library(lib: Any, path: str = "wgfmu.dll") -> None:
    """Set ``argtypes``/``restype`` of every function of ``C_SIGNATURES`` on ``lib``; raises ``WgfmuError``
    (``WGFMU_LIBRARY_ERROR``) naming the functions ``lib`` does not export."""
    missing = []
    for name in sorted(C_SIGNATURES):
        try:
            func = getattr(lib, name)
        except AttributeError:
            missing.append(name)
            continue
        func.argtypes = argtypes_of(name)
        func.restype = RESTYPE
    if missing:
        raise WgfmuError(LIBRARY_ERROR, error_text(LIBRARY_ERROR, f"{path} does not export {', '.join(missing)}: "
                                                                  "install library >= A.03.00"))


# -- PE reader (pure Python; nothing is loaded) ------------------------------------------------------------------------

MACHINES: Final[dict[int, str]] = {0x8664: "x64", 0x14C: "x86"}
"""COFF machine -> name (IMAGE_FILE_MACHINE_AMD64, IMAGE_FILE_MACHINE_I386)."""
PE32_MAGIC: Final = 0x10B
PE32_PLUS_MAGIC: Final = 0x20B
IMAGE_FILE_DLL: Final = 0x2000
MAX_LIBRARY_BYTES: Final = 64 * 1024 * 1024
_FIXED_INFO_SIGNATURE: Final = struct.pack("<I", 0xFEEF04BD)
_FILE_VERSION_KEY: Final = "FileVersion\0".encode("utf-16-le")


class PeError(ValueError):
    """The bytes are not a readable PE image (truncated, not a Windows DLL, an offset outside the file)."""


@dataclass(frozen=True)
class PeImage:
    """What ``read_pe`` found: COFF machine, optional-header magic, the DLL flag, the exported names (``None``
    without an export directory) and the file version (``None`` without a version resource)."""

    machine: int
    magic: int
    dll: bool
    exports: frozenset[str] | None
    file_version: str | None

    @property
    def machine_name(self) -> str:
        return MACHINES.get(self.machine, "unknown")


def _u16(data: bytes, offset: int) -> int:
    if offset < 0 or offset + 2 > len(data):
        raise PeError(f"truncated at offset {offset}")
    return int.from_bytes(data[offset:offset + 2], "little")


def _u32(data: bytes, offset: int) -> int:
    if offset < 0 or offset + 4 > len(data):
        raise PeError(f"truncated at offset {offset}")
    return int.from_bytes(data[offset:offset + 4], "little")


def _c_string(data: bytes, offset: int) -> str:
    end = data.find(b"\0", offset, offset + 512)
    if offset < 0 or end < 0:
        raise PeError(f"unterminated name at offset {offset}")
    return data[offset:end].decode("ascii", errors="replace")


def _file_version(blob: bytes) -> str | None:
    """The ``FileVersion`` string of a version resource, else the numeric file version of its
    ``VS_FIXEDFILEINFO`` (``major.minor.build.revision``), else ``None``."""
    key = blob.find(_FILE_VERSION_KEY)
    if key >= 0:
        start = key + len(_FILE_VERSION_KEY)
        while start + 1 < len(blob) and blob[start:start + 2] == b"\0\0" and start < key + len(_FILE_VERSION_KEY) + 4:
            start += 2  # padding to the 32-bit boundary
        end = start
        while end + 1 < len(blob) and blob[end:end + 2] != b"\0\0":
            end += 2
        text = blob[start:end].decode("utf-16-le", errors="replace").strip()
        if text and text.isprintable():
            return text
    sig = blob.find(_FIXED_INFO_SIGNATURE)
    if sig >= 0 and sig + 16 <= len(blob):
        ms, ls = _u32(blob, sig + 8), _u32(blob, sig + 12)
        return f"{ms >> 16}.{ms & 0xFFFF}.{ls >> 16}.{ls & 0xFFFF}"
    return None


def read_pe(data: bytes) -> PeImage:
    """Parse the headers, export names and version resource of a PE image (``PeError`` when it is not one)."""
    if data[:2] != b"MZ":
        raise PeError("no MZ header: not a Windows DLL")
    pe = _u32(data, 0x3C)
    if data[pe:pe + 4] != b"PE\0\0":
        raise PeError("no PE signature: not a Windows DLL")
    coff = pe + 4
    machine, sections = _u16(data, coff), _u16(data, coff + 2)
    opt_size, characteristics = _u16(data, coff + 16), _u16(data, coff + 18)
    opt = coff + 20
    magic = _u16(data, opt)
    if magic == PE32_PLUS_MAGIC:
        count_at, dirs_at = opt + 108, opt + 112
    elif magic == PE32_MAGIC:
        count_at, dirs_at = opt + 92, opt + 96
    else:
        raise PeError(f"unknown optional header magic 0x{magic:x}")
    n_dirs = _u32(data, count_at)

    def directory(index: int) -> tuple[int, int]:
        at = dirs_at + 8 * index
        if index >= n_dirs or at + 8 > opt + opt_size:
            return 0, 0
        return _u32(data, at), _u32(data, at + 4)

    table = opt + opt_size
    spans = []
    for i in range(sections):
        header = table + 40 * i
        vsize, va = _u32(data, header + 8), _u32(data, header + 12)
        raw_size, raw_at = _u32(data, header + 16), _u32(data, header + 20)
        spans.append((va, max(vsize, raw_size), raw_at, raw_size))

    def offset(rva: int) -> int:
        for va, size, raw_at, raw_size in spans:
            if va <= rva < va + size:
                if rva - va >= raw_size:
                    raise PeError(f"RVA 0x{rva:x} has no data in the file")
                return raw_at + rva - va
        raise PeError(f"RVA 0x{rva:x} lies in no section")

    exports: frozenset[str] | None = None
    export_rva, _ = directory(0)
    if export_rva:
        at = offset(export_rva)
        n_names, names_rva = _u32(data, at + 24), _u32(data, at + 32)
        if n_names > 65_536:
            raise PeError(f"implausible export count {n_names}")
        names_at = offset(names_rva) if n_names else 0
        exports = frozenset(_c_string(data, offset(_u32(data, names_at + 4 * i))) for i in range(n_names))
    version = None
    resource_rva, resource_size = directory(2)
    if resource_rva and resource_size:
        at = offset(resource_rva)
        version = _file_version(data[at:at + resource_size])
    return PeImage(machine, magic, bool(characteristics & IMAGE_FILE_DLL), exports, version)


# -- Locating and probing the library ----------------------------------------------------------------------------------


def python_bits() -> int:
    """Pointer width of this interpreter (64 on the lab PC's Python 3.12 x64)."""
    return struct.calcsize("P") * 8


def library_path(settings: Settings | WgfmuSettings, environ: Mapping[str, str] | None = None) -> str:
    """The configured ``wgfmu.library`` (as given; an absolute path is expected), else the installer's default
    ``%SystemRoot%\\System32\\wgfmu.dll`` (``C:\\Windows`` when ``SystemRoot`` is unset)."""
    wgfmu = settings.wgfmu if isinstance(settings, Settings) else settings
    if wgfmu.library.strip():
        return wgfmu.library.strip()
    env = os.environ if environ is None else environ
    root = env.get("SystemRoot") or env.get("SYSTEMROOT") or "C:\\Windows"
    return str(PureWindowsPath(root, "System32", "wgfmu.dll"))


def _read_library(path: str) -> bytes:
    """The DLL's bytes (``OSError`` when unreadable; ``PeError`` when implausibly large)."""
    target = Path(path)
    size = target.stat().st_size
    if size > MAX_LIBRARY_BYTES:
        raise PeError(f"{size} bytes: too large for a wgfmu.dll")
    return target.read_bytes()


INSTALL_HINT: Final = ("install library >= A.03.00 (B1530A WGFMU Instrument Library, current A.04.00.2440.5403: x64 "
                       "wgfmu.dll in System32) or set wgfmu.library to the x64 DLL")
NOT_WINDOWS: Final = ("wgfmu.dll loads only on Windows (the lab PC, backend visa); on this OS the WGFMU library is "
                      "the simulator's")

_PROBES: dict[tuple[str, str, int], tuple[tuple[int, int], DllProbe]] = {}
"""Probe cache: (path, platform, bits) -> ((mtime_ns, size), probe); a changed file is probed again."""


def probe_library(path: str, *, platform: str | None = None, bits: int | None = None) -> DllProbe:
    """Whether this Python can load the WGFMU library at ``path`` (see the module docstring); never raises and never
    loads the DLL. ``platform``/``bits`` default to this interpreter's (tests inject them)."""
    system = sys.platform if platform is None else platform
    width = python_bits() if bits is None else bits
    try:
        return _probe(path, system, width)
    except Exception as exc:  # noqa: BLE001 - the probe reports, never raises
        return DllProbe(path=path, exists=False, python_bits=width, loadable=False,
                        message=f"{path}: probe failed ({type(exc).__name__}: {exc})")


def _probe(path: str, system: str, width: int) -> DllProbe:
    windows = system == "win32"
    target = Path(path)
    try:
        present = target.is_file()  # a missing file, folder or drive reads as absent (pathlib ignores those errors)
    except OSError as exc:
        return DllProbe(path=path, exists=False, python_bits=width, loadable=False,
                        message=f"{path} cannot be read ({exc})" + ("" if windows else f"; {NOT_WINDOWS}"))
    if not present:
        if not windows:
            return DllProbe(path=path, exists=False, python_bits=width, loadable=False, message=NOT_WINDOWS)
        return DllProbe(path=path, exists=False, python_bits=width, loadable=False,
                        message=f"{path} not found: {INSTALL_HINT}")
    key = (path, system, width)
    stat = target.stat()
    stamp = (stat.st_mtime_ns, stat.st_size)
    cached = _PROBES.get(key)
    if cached is not None and cached[0] == stamp:
        return cached[1]
    probe = _probe_file(path, windows, width)
    _PROBES[key] = (stamp, probe)
    return probe


def _probe_file(path: str, windows: bool, width: int) -> DllProbe:
    base: dict[str, Any] = {"path": path, "exists": True, "python_bits": width}
    try:
        image = read_pe(_read_library(path))
    except (OSError, PeError) as exc:
        return DllProbe(**base, machine="unknown", loadable=False,
                        message=f"{path} is not a readable Windows DLL ({exc}): {INSTALL_HINT}")
    machine = image.machine_name
    base.update(machine=machine, file_version=image.file_version)
    x64 = machine == "x64" and image.magic == PE32_PLUS_MAGIC
    # exports are judged on an x64 image only (32-bit stdcall exports carry decorated names: _name@bytes)
    missing = sorted(set(C_SIGNATURES) - (image.exports or frozenset())) if x64 else []
    base["missing_exports"] = missing
    facts = f"{path}: {machine} DLL (machine 0x{image.machine:x})" + (
        f", file version {image.file_version}" if image.file_version else "")
    problems = []
    if machine == "x86":
        problems.append(f"a 32-bit DLL cannot load into {width}-bit Python: {INSTALL_HINT}")
    elif not x64:
        problems.append(f"not an x64 DLL: {INSTALL_HINT}")
    if not image.dll:
        problems.append("the image is not a DLL")
    if width != 64:
        problems.append(f"this Python is {width}-bit; the x64 library needs 64-bit Python (uv python install 3.12)")
    if x64 and image.exports is None:
        problems.append(f"no export table (the binding needs {len(C_SIGNATURES)} functions): {INSTALL_HINT}")
    elif missing:
        shown = ", ".join(missing[:4]) + (f" (+{len(missing) - 4} more)" if len(missing) > 4 else "")
        problems.append(f"{len(missing)} function(s) the binding needs are not exported ({shown}): {INSTALL_HINT}")
    if problems:
        return DllProbe(**base, loadable=False, message=f"{facts}; " + "; ".join(problems))
    exported = f"{len(C_SIGNATURES)}/{len(C_SIGNATURES)} exports"
    if not windows:
        return DllProbe(**base, loadable=False, message=f"{facts}, {exported}; {NOT_WINDOWS}")
    return DllProbe(**base, loadable=True, message=f"{facts}, {exported}; loadable by this {width}-bit Python")


# -- Argument conversion -----------------------------------------------------------------------------------------------


class ArgumentRefused(WgfmuError):
    """An argument no C function can take (not ASCII, not a C number, an unknown literal): refused before the
    library with the code the library itself would return; its text is queued for ``errors()`` like the library's
    own strings."""


def _refuse(fn: str, code: int, detail: str) -> ArgumentRefused:
    return ArgumentRefused(code, f"{fn}: {error_text(code, detail)}", function=fn)


def _ascii(fn: str, value: object, what: str) -> bytes:
    """``value`` as an ASCII C string (``WGFMU_ILLEGAL_STRING`` for anything else, nothing is called)."""
    if not isinstance(value, str) or not value or "\0" in value:
        raise _refuse(fn, ILLEGAL_STRING, f"{what} {value!r}")
    try:
        return value.encode("ascii")
    except UnicodeEncodeError:
        raise _refuse(fn, ILLEGAL_STRING, f"{what} {value!r} is not ASCII") from None


def _int(fn: str, value: object, what: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int | np.integer):
        raise _refuse(fn, PARAMETER_OUT_OF_RANGE, f"{what} {value!r}")
    number = int(value)
    if not -(2 ** 31) <= number < 2 ** 31:
        raise _refuse(fn, PARAMETER_OUT_OF_RANGE, f"{what} {number} exceeds C int")
    return number


def _double(fn: str, value: object, what: str) -> float:
    if isinstance(value, bool) or not isinstance(value, int | float | np.integer | np.floating) \
            or not math.isfinite(float(value)):
        raise _refuse(fn, PARAMETER_OUT_OF_RANGE, f"{what} {value!r}")
    return float(value)


def _code(fn: str, table: Mapping[Any, int], value: object, what: str) -> int:
    """The ``wgfmu.h`` code of a Python literal (``OPERATION_MODES`` ...); ``WGFMU_PARAMETER_OUT_OF_RANGE`` for an
    unknown one. Flags (``bool``) are mapped by their callers."""
    try:
        code = None if isinstance(value, bool) else table.get(value)
    except TypeError:  # unhashable
        code = None
    if code is None:
        raise _refuse(fn, PARAMETER_OUT_OF_RANGE, f"{what} {value!r} (allowed: {', '.join(map(str, table))})")
    return code


def _doubles(fn: str, values: Sequence[float], what: str) -> np.ndarray:
    try:
        array = np.ascontiguousarray(np.asarray(values, dtype=np.float64).ravel())
    except (TypeError, ValueError):
        raise _refuse(fn, PARAMETER_OUT_OF_RANGE, f"{what} is not numeric") from None
    if not np.all(np.isfinite(array)):
        raise _refuse(fn, PARAMETER_OUT_OF_RANGE, f"non-finite {what}")
    return array


_DOUBLE_P: Final = ctypes.POINTER(ctypes.c_double)
_INT_P: Final = ctypes.POINTER(ctypes.c_int)


def _ptr(array: np.ndarray, kind: Any) -> Any:
    """A ctypes pointer to the first element of ``array`` (kept alive by the caller during the call)."""
    return array.ctypes.data_as(kind)


