"""``WgfmuDll``: ``WgfmuApi`` over the Keysight B1530A WGFMU instrument library ``wgfmu.dll`` (blueprint v2 2.4,
decision 6; WP10.2). The only module that imports ``ctypes`` and the only one that loads ``wgfmu.dll`` (lints
``tests/unit/test_lint_ctypes.py``, ``tests/adapters/test_windows_readiness.py``).

Binding. ``C_SIGNATURES`` is the C prototype of every function the protocol needs, exactly the functions named by
``api.C_FUNCTIONS``. It is generated by ``scripts/gen_wgfmu_signatures.py`` from the API extract
``references/manuals/structured/b1530a-wgfmu-api-reference.yaml``: the extract names each function and the manual
pages of its "Syntax" line (WG5 = Ed. 5), whose prototype gives the parameter order and types; the base type of every
parameter must match the extract and the prototype must be the same in Ed. 8 (WG, the library generation the lab
installs). Never edit the block by hand: regenerate it (``--check`` in the tests). Every function returns ``int``
(``WGFMU_NO_ERROR`` 0 or a negative code, WG p148 (4-78)). ``argtypes``/``restype`` are set from the table when the
library is loaded; strings go in as ASCII ``c_char_p``, arrays as numpy buffers, outputs through ``byref``.

Loading. ``WgfmuDll(path)`` only stores the path: nothing is loaded until the first call, and before that call the
library is probed (``probe()``) and loaded only when the probe says it can be (``ctypes.WinDLL`` on Windows, a 64-bit
DLL for a 64-bit Python with every export of the table). On the Mac a visa bus therefore carries a ``WgfmuDll`` that
is constructed and never loaded; every call fails with ``WGFMU_LIBRARY_ERROR``.

Errors. A negative return code raises ``WgfmuError``: the library's queued error strings are read right away with
``WGFMU_getErrorSize``/``WGFMU_getError`` (the manual's ``checkError`` pattern, WG p97 (4-27)); the last one belongs to
the call and is the exception's text, and all of them stay available to ``errors()``, so the queue reads as on the
simulator. For ``WGFMU_FW_ERROR`` the firmware code (3000-3999) is taken from that string. An argument no C function
can take (not ASCII, not a finite C number, an unknown literal) is refused before the library with the code the
library would return (``ArgumentRefused``) and queued the same way. Exceptions of the call itself (an access violation
surfaces as ``OSError``, a marshalling error as ``ctypes.ArgumentError``) become ``WGFMU_LIBRARY_ERROR``.
TODO(verify) at bring-up L8: the text format of the library's error strings (firmware code position) and the real
codes of firmware errors (blueprint 7.6 item 5).

Readback. ``measure_values`` reads in chunks of ``READBACK_CHUNK`` (100,000) values per ``WGFMU_getMeasureValues``
call into preallocated numpy arrays, as the lab code does (``lwp/1530/LFN_noise_meas.cpp``); a short chunk ends the
read, and ``RESULT_NOT_READY`` or ``PARAMETER_OUT_OF_RANGE`` (offset at the end) after the first chunk returns what was
read, as one call of the simulator does.

Probe (``WgfmuDll.locate(settings)``, ``probe()``, ``probe_library``): never raises and never loads anything. It finds
the configured ``wgfmu.library`` or the installer's default ``%SystemRoot%\\System32\\wgfmu.dll``, reads the PE header
in pure Python (``read_pe``: machine 0x8664 = x64, 0x14c = x86; the export names; the file version from the version
resource) and says whether this Python can load it. A 32-bit DLL is not loadable: "install library >= A.03.00" (the
first release with the x64 DLL in System32, Keysight release notes 9018-80226; no 32-bit bridge). Off Windows nothing
is loadable (WARN on the Mac); tests inject ``platform``. TODO(verify) at L0: the version resource form of the
installed library (``A.04.00.2440.5403`` string or numeric only).
"""

